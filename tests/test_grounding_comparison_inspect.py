def budget(requests=30):
    """Finite test reservations leave ample headroom for three invented stages."""
    return RunBudget(
        currency_cap="10", request_cap=requests, output_cap=100000, wall_seconds=60, paid=False
    )


def envelopes(condition, *, disagree=False, classification="substantive"):
    """Reuse documented protocol fixtures, replacing their output with stage-valid decisions."""
    packet = sample().packet
    payloads = {
        "abstention": abstention_input(packet),
        "P2": semantics.point_inputs(packet)[0],
        "conclusion": semantics.conclusion_input(packet, [{"point_id": "P2", "supported": True}]),
    }
    result = {}
    for key, payload in payloads.items():
        kind = "point" if key == "P2" else key
        if kind == "abstention":
            probabilities = {
                "substantive": 0.9 if classification == "substantive" else 0.1,
                "clean_abstention": 0.9 if classification == "clean_abstention" else 0.1,
            }
            decision = {"classification": classification}
        elif kind == "point":
            probabilities = {"supported": 0.9}
            decision = {
                "point_id": "P2",
                "supported": True,
                "locators": [{"citation_id": "S1", "excerpt": "Not a literal quote"}],
            }
        else:
            probabilities = {
                "clean_abstention": 0.1,
                "conclusion_supported": 0.9,
                "review_0": 0.1 if disagree else 0.9,
            }
            decision = {
                "clean_abstention": False,
                "conclusion_supported": True,
                "point_reviews": [{"point_id": "P2", "supported": not disagree}],
            }
        response = native_response(condition, kind, payload, probabilities)
        if condition.kind == "generation":
            text = json.dumps(decision)
            if condition.api == "openai_responses":
                response["output"][0]["content"][0]["text"] = text
            elif condition.api == "anthropic_messages":
                response["content"][0]["text"] = text
            else:
                response["choices"][0]["message"]["content"] = text
        result[key] = response
    return {"fixture": result}


def run(tmp_path, condition, fixtures, *, run_budget=None):
    """Return the durable result generated by the real Inspect scorer and log writer."""
    logs = runner.evaluate_comparison(
        [sample()], condition, tmp_path, run_budget or budget(), fixtures=fixtures
    )
    assert logs[0].status == "success"
    assert list((tmp_path / "inspect").glob("*.eval"))
    return logs[0].samples[0].scores["comparison_scorer"].metadata["comparison_record"]


