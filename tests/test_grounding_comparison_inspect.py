def test_full_pipeline_stage_prompts_and_fresh_observations(tmp_path):
    """Different stage prompts bind receipts while review receives newly observed decisions."""
    from er_commons.artifact_io import stable_json_sha256

    condition = CONDITIONS["openai_generation"]
    fixtures = envelopes(condition)
    fixtures["fixture"]["P2"]["output"][0]["content"][0]["text"] = json.dumps(
        {"point_id": "P2", "supported": False}
    )
    fixtures["fixture"]["conclusion"]["output"][0]["content"][0]["text"] = json.dumps(
        {
            "clean_abstention": False,
            "conclusion_supported": True,
            "point_reviews": [{"point_id": "P2", "supported": False}],
        }
    )
    overrides = {
        "point": "Invented point instructions.",
        "conclusion": "Invented review instructions.",
    }
    logs = runner.evaluate_comparison(
        [sample()], condition, tmp_path, budget(), fixtures=fixtures, stage_prompts=overrides
    )
    record = logs[0].samples[0].scores["comparison_scorer"].metadata["comparison_record"]
    assert record["status"] == "scored" and record["score"] == 1
    assert not any(stage["reused"] for stage in record["stages"])
    for path in (tmp_path / "requests").rglob("request.json"):
        request = json.loads(path.read_text())
        kind = request["body"]["text"]["format"]["name"].removeprefix("grounding_")
        assert request["body"]["input"][0]["content"][0]["text"] == overrides.get(
            kind, semantics.stage_prompt(kind)
        )
        intent = json.loads((path.parent / "intent.json").read_text())
        assert intent["request_sha256"] == stable_json_sha256(request)
        assert intent["preflight"]["counter"]["request_sha256"] == stable_json_sha256(request)
        if kind == "conclusion":
            payload = json.loads(request["body"]["input"][1]["content"][0]["text"])
            assert payload["point_assessments"] == [{"point_id": "P2", "supported": False}]
            expected = semantics.conclusion_input(
                sample().packet, [{"point_id": "P2", "supported": False}]
            )
            assert payload == expected
    changed = {**overrides, "point": "Changed point instructions."}
    logs = runner.evaluate_comparison(
        [sample()], condition, tmp_path, budget(), fixtures=fixtures, stage_prompts=changed
    )
    record = logs[0].samples[0].scores["comparison_scorer"].metadata["comparison_record"]
    assert record["status"] == "receipt_error"
    assert "identity" in record["stages"][1]["error"].lower()
    assert len(list((tmp_path / "requests").rglob("completion.json"))) == 3


