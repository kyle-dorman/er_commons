def test_concurrent_counter_return_cannot_dispatch_after_shared_halt(tmp_path, monkeypatch):
    """A failed sibling prevents a pending exact counter from reserving generation."""
    condition = CONDITIONS["openai_generation"]
    run_budget = budget()
    counter_started = asyncio.Event()
    release_counter = asyncio.Event()
    calls = []
    monkeypatch.setattr(runner, "_headers", lambda *args: {})

    async def transport(endpoint, body, headers, timeout):
        calls.append(endpoint)
        if not endpoint.endswith("/input_tokens"):
            pytest.fail("A halted run cannot dispatch the pending generation")
        counter_started.set()
        await release_counter.wait()
        return {"input_tokens": 100}

    monkeypatch.setattr(runner, "_post", transport)

    async def interleaved():
        task = asyncio.create_task(
            runner.run_comparison_stage(
                condition,
                "abstention",
                abstention_input(sample().packet),
                tmp_path / "pending",
                run_budget,
            )
        )
        await counter_started.wait()
        run_budget.halt_reason = "transport_error"
        release_counter.set()
        return await task

    result = asyncio.run(interleaved())
    assert result["status"] == "run_halted"
    assert run_budget.halt_reason == "transport_error"
    assert run_budget.requests_reserved == 0 and len(calls) == 1
    assert not (tmp_path / "pending").exists()
